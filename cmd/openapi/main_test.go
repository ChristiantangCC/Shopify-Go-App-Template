package main

import (
	"bytes"
	"os"
	"testing"
)

// The committed spec must match the code: regenerate it with
// `bun run codegen:api` after changing an API type or operation.
func TestCommittedSpecIsCurrent(t *testing.T) {
	var generated bytes.Buffer
	if err := run(&generated); err != nil {
		t.Fatal(err)
	}
	committed, err := os.ReadFile("../../api/openapi.yaml")
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(generated.Bytes(), committed) {
		t.Fatal("api/openapi.yaml is stale: run `bun run codegen:api` and commit the result")
	}
}
